"""User config: plain environment variables, with a generated .env fallback.

One mechanism for CLI and bot alike -- the same three variables work
everywhere, from the shell, a CI box, or the bot container:

    GEMINI_API_KEY   # your BYOK key (required for the smart brain)
    GEMINI_MODEL     # optional, defaults to DEFAULT_MODEL below

Precedence: real environment wins; otherwise $SHREK_HOME/.env is loaded
(once a process is inside Docker with SHREK_HOME=/data, that is the same
volume the ledger uses, so an edited variable survives restarts).
"""

import os
import stat
import sys
from getpass import getpass
from pathlib import Path

CONFIG_DIR = Path(os.environ.get("SHREK_HOME", "~/.shrek")).expanduser()
ENV_PATH = CONFIG_DIR / ".env"
DEFAULT_MODEL = "gemini-3.8-flash"

_REPO = "https://github.com/YOURNAME/shrek"
_NEED_KEY = (
    "shrek: no GEMINI_API_KEY configured -- running on the deterministic\n"
    "  regex brain only. Fix one of two ways:\n"
    f"    a) `shrek setup`   (writes {ENV_PATH})\n"
    "    b) export GEMINI_API_KEY=...   (add GEMINI_MODEL=... optionally)\n"
    "  Every surface (CLI, REPL, bot) picks these up."
)


def _load_dotenv_file() -> None:
    """Populate os.environ from SHREK_HOME/.env once, without overriding
    variables the user already exported."""
    try:
        from dotenv import load_dotenv

        load_dotenv(ENV_PATH, override=False)
    except ImportError:
        pass


def gemini_key() -> "str | None":
    _load_dotenv_file()
    return (os.environ.get("GEMINI_API_KEY") or "").strip() or None


def model() -> str:
    _load_dotenv_file()
    return (os.environ.get("GEMINI_MODEL") or "").strip() or DEFAULT_MODEL


def is_configured() -> bool:
    return gemini_key() is not None


def _upsert_env(pairs: dict) -> Path:
    """Insert/replace variables in SHREK_HOME/.env, keep the rest, 0600.
    Also refreshes os.environ so the same running process (REPL, bot /key)
    sees the change; a persistent real-environment export still wins in
    any *new* process, per the documented precedence."""
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    lines = ENV_PATH.read_text(encoding="utf-8").splitlines() if ENV_PATH.exists() else []
    for name, value in pairs.items():
        pat = f"{name}="
        lines = [ln for ln in lines if not ln.startswith(pat)]
    lines = [ln for ln in lines if not ln.startswith("# generated")]
    lines = ["# generated by shrek setup -- edit freely; exported env vars override this file",
             *lines]
    lines += [f"{k}={v}" for k, v in pairs.items() if v is not None]
    ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(ENV_PATH, stat.S_IRUSR | stat.S_IWUSR)
    for name, value in pairs.items():
        os.environ[name] = value
    return ENV_PATH


def save(gemini_key: "str | None" = None, model: "str | None" = None) -> Path:
    pairs = {}
    if gemini_key is not None:
        pairs["GEMINI_API_KEY"] = gemini_key
    if model is not None:
        pairs["GEMINI_MODEL"] = model
    if not pairs:
        raise ValueError("save() needs a key or model")
    return _upsert_env(pairs)


def save_model(model: str) -> Path:
    return save(model=model)


def forget_key() -> Path:
    """Drop GEMINI_API_KEY from the .env (bot /forgetkey). Model survives."""
    os.environ.pop("GEMINI_API_KEY", None)
    if ENV_PATH.exists():
        lines = ENV_PATH.read_text(encoding="utf-8").splitlines()
        lines = [ln for ln in lines if not ln.startswith("GEMINI_API_KEY=")]
        ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
        os.chmod(ENV_PATH, stat.S_IRUSR | stat.S_IWUSR)
    return ENV_PATH


def ensure_configured() -> bool:
    """True when a key exists; interactive first run runs the wizard, which
    generates the .env; headless prints the pointer and never crashes."""
    if is_configured():
        return True
    if not sys.stdin.isatty():
        print(_NEED_KEY, file=sys.stderr)
        return False
    wizard()
    return is_configured()


def wizard() -> None:
    """Interactive setup: reads key + model choice and writes $SHREK_HOME/.env."""
    print("shrek setup -- the ogre needs one key and a model.")
    print("  Get a key: https://aistudio.google.com/apikey")
    key = ""
    while not key:
        try:
            key = getpass("paste your Gemini API key (hidden, never echoed): ").strip()
        except EOFError:
            return
        if not key:
            print("  a key is required for the smart brain (Ctrl-C to skip).")
    from shrek import llm

    models = llm.list_models(key)
    print(f"\n  model list (Enter = {models[0]}):")
    for i, name in enumerate(models[1:], start=1):
        print(f"  {i}. {name}")
    choice = input("model number or name (Enter = default): ").strip()
    model = models[0]
    if choice == "":
        pass
    elif choice.isdigit() and 1 <= int(choice) < len(models):
        model = models[int(choice)]
    elif choice in models:
        model = choice
    else:
        print(f"  not in the list; defaulting to {model}")
    path = save(key, model)
    print(f"\nwritten: {path} (0600)")
    print("change the model any time: edit GEMINI_MODEL in that file, or run `shrek model <name>`.")
    print("your env vars (GEMINI_API_KEY / GEMINI_MODEL) always override the file.")
